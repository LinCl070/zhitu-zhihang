"""Build two government-source knowledge-base documents for FastGPT review."""

from pathlib import Path

from docx import Document

from build_submission_docs import add_paragraph, add_table, add_title_block, configure_document


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "knowledge-base" / "upload-ready"


def add_boundary(doc: Document, audience: str) -> None:
    doc.add_heading("一 使用范围", level=1)
    add_paragraph(
        doc,
        f"本材料面向{audience}，依据政府部门和国家公共就业服务平台公开信息整理。"
        "它只用于一般性信息检索和准备建议，不构成具体资格认定、补贴额度、录用结果或办理时限承诺。"
        "涉及地方口径、材料清单、申报窗口和个人资格时，应以办理地人力资源社会保障部门、教育部门或学校就业部门最新通知为准。",
    )


def add_source_section(doc: Document, rows: list[tuple[str, str, str]]) -> None:
    doc.add_heading("五 来源与更新规则", level=1)
    add_paragraph(
        doc,
        "所有来源均应保留原始网页链接和发布日期。资料管理员应至少每学期复核一次；"
        "若原页面失效、政策被修订或适用范围变化，应下线旧版本并重新审核。",
    )
    add_table(doc, ["来源", "发布信息", "原始链接"], rows, [3100, 2250, 4010])


